const MHWElementState=require('../element-state.js');
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const start=html.indexOf('function comparisonPowerIndex(');
const end=html.indexOf('\nfunction comparisonDisplayNumber(',start);
assert.ok(start>=0&&end>start);
const api=vm.runInNewContext(html.slice(start,end)+'\n({comparisonPowerIndex,comparisonPowerChange})',require('../tools/element-vm-test-setup.cjs').context());
const build=(attack,profile='BOW_STANDARD')=>({...MHWElementState.fromValue(0,'none'),kind:'bow',power:{profileId:profile,normal:{comparisonPower:attack,physical:attack,element:0,special:0},maximum:{comparisonPower:attack,physical:attack,element:0,special:0}}});
const base=build(200);
test('skill-driven build power increase changes baseline ratio',()=>assert.equal(api.comparisonPowerIndex(build(220),base).normal,110.00000000000001));
test('skill-driven build power decrease changes baseline ratio',()=>assert.equal(api.comparisonPowerIndex(build(180),base).normal,90));
test('power comparison blocks both missing fixed profiles',()=>assert.equal(api.comparisonPowerIndex(build(200,null),build(200,null)),null));
test('power comparison blocks missing candidate profile',()=>assert.equal(api.comparisonPowerIndex(build(200,null),base),null));
test('power comparison blocks missing baseline profile',()=>assert.equal(api.comparisonPowerIndex(base,build(200,null)),null));
test('power comparison blocks different weapon types',()=>assert.equal(api.comparisonPowerIndex({...base,kind:'hammer'},base),null));
test('power comparison blocks different fixed routes',()=>assert.equal(api.comparisonPowerIndex(build(200,'OTHER'),base),null));
test('power change cannot bypass missing route identity',()=>assert.equal(api.comparisonPowerChange(build(200,null),build(200,null)),null));
